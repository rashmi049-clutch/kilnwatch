"""
Point-by-point record of the analyst's Google Earth audits, for the report appendix.
Reads the audit CSVs (filled in as verdicts arrive) and writes report/audit_tables.tex,
which ncr_kilns_report.tex \\input s. Rerun before building the report.

    outputs/tables/kiln_audit_25.csv    audit 1, 25 random kilns (whole layer, before cleaning)
    outputs/tables/kiln_audit2_30.csv   audit 2, 30 random kilns not yet checked by eye
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
LABEL = {"active": "active", "relict": "relict", "not_kiln": "not a kiln", "unclear": "unclear"}


def tex(s):
    s = "" if pd.isna(s) else str(s)
    for a, b in [("\\", "/"), ("&", "\\&"), ("%", "\\%"), ("_", "\\_"), ("#", "\\#"), ("$", "\\$"),
                 ("–", "--"), ("—", "---"), ("≈", "$\\approx$")]:
        s = s.replace(a, b)
    return s


def table(csv, title, detail_col):
    a = pd.read_csv(ROOT / csv, dtype=str)
    done = a.verdict.notna() & (a.verdict != "")
    counts = a.loc[done, "verdict"].map(LABEL).value_counts()
    summary = ", ".join(f"{n} {k}" for k, n in counts.items()) or "none yet"
    rows = []
    for r in a.itertuples():
        detail = getattr(r, detail_col, "") if detail_col in a else ""
        if (pd.isna(detail) or detail in ("", "not specified")) and "note" in a:
            detail = r.note if not pd.isna(r.note) else ""
        if detail == "not specified":
            detail = ""
        rows.append(f"{r.audit_no} & {r.det_index} & {float(r.lat):.5f} & {float(r.lon):.5f} & "
                    f"{tex(LABEL.get(r.verdict, '') if not pd.isna(r.verdict) else '--- pending')} & "
                    f"{tex(r.audited_by) if 'audited_by' in a and not pd.isna(r.audited_by) else ''} & {tex(detail)} \\\\")
    return f"""\\subsection*{{{title}}}
Checked in Google Earth Pro historical imagery (Maxar, Airbus) by Rashmi Sinha.
{int(done.sum())} of {len(a)} points decided: {summary}. Source: \\texttt{{{tex(csv)}}}.
{{\\footnotesize
\\begin{{longtable}}{{@{{}}r r r r P{{1.5cm}} P{{1.9cm}} P{{5.4cm}}@{{}}}}
\\toprule
No. & Det.\\ id & Lat (N) & Lon (E) & Verdict & Audited by & Imagery seen / note \\\\
\\midrule
\\endhead
{chr(10).join(rows)}
\\bottomrule
\\end{{longtable}}
}}
"""


out = ("% Generated by analysis/audit_tables.py from the audit CSVs - do not edit by hand.\n"
       + table("outputs/tables/kiln_audit_25.csv", "Audit 1: 25 random kilns (whole layer)", "note")
       + table("outputs/tables/kiln_audit2_30.csv", "Audit 2: 30 random kilns not checked by eye", "images_seen"))
(ROOT / "report/audit_tables.tex").write_text(out, encoding="utf-8")
print("wrote report/audit_tables.tex")
